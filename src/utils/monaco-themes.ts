import type * as monaco from 'monaco-editor'

const makeTheme = (
  base: 'vs' | 'vs-dark',
  bg: string,
  fg: string,
  cursor: string,
  selection: string,
  lineHighlight: string,
  gutterBg: string,
  gutterFg: string,
  gutterActiveFg: string,
  comment: string,
  keyword: string,
  string_: string,
  number_: string,
  type_: string,
  function_: string,
  variable: string,
  operator: string,
): monaco.editor.IStandaloneThemeData => ({
  base,
  inherit: true,
  rules: [
    { token: 'comment', foreground: comment, fontStyle: 'italic' },
    { token: 'keyword', foreground: keyword },
    { token: 'string', foreground: string_ },
    { token: 'number', foreground: number_ },
    { token: 'type', foreground: type_ },
    { token: 'function', foreground: function_ },
    { token: 'variable', foreground: variable },
    { token: 'operator', foreground: operator },
    { token: 'delimiter', foreground: fg },
    { token: 'identifier', foreground: fg },
    { token: 'label', foreground: type_ },
    { token: 'directive', foreground: keyword },
  ],
  colors: {
    'editor.background': bg,
    'editor.foreground': fg,
    'editorCursor.foreground': cursor,
    'editor.selectionBackground': selection,
    'editor.selectionHighlightBackground': selection + '80',
    'editor.lineHighlightBackground': lineHighlight,
    'editorLineNumber.foreground': gutterFg,
    'editorLineNumber.activeForeground': gutterActiveFg,
    'editorGutter.background': gutterBg,
    'editorGutter.modifiedBackground': '#82aaff44',
    'editorGutter.addedBackground': '#c3e88d44',
    'editorGutter.deletedBackground': '#f0717844',
    'editorBracketMatch.background': selection,
    'editorBracketMatch.border': fg + '40',
    'editor.findMatchHighlightBackground': '#ffd70022',
    'editor.wordHighlightBackground': '#ffffff10',
    'editorIndentGuide.background': selection + '66',
    'editorIndentGuide.activeBackground': selection,
    'editorWhitespace.foreground': selection,
    'editorWidget.background': bg,
    'editorWidget.border': lineHighlight,
    'input.background': bg,
    'input.foreground': fg,
    'input.border': lineHighlight,
    'focusBorder': cursor + '80',
    'list.activeSelectionBackground': selection,
    'list.hoverBackground': lineHighlight,
    'list.focusBackground': lineHighlight,
    'scrollbar.shadow': '#00000044',
    'scrollbarSlider.background': selection + '80',
    'scrollbarSlider.hoverBackground': selection,
    'scrollbarSlider.activeBackground': selection,
    'minimap.background': bg,
  },
})

